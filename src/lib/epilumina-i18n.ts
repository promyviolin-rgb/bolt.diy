export function useT(lang: string) {
  return (path: string): any => {
    const parts = path.split(".");
    let node: any = translations[lang];
    for (const p of parts) node = node?.[p];
    if (node === undefined) {
      // Fallback chain: requested lang → English → Polish
      node = translations.en;
      for (const p of parts) node = node?.[p];
    }
    if (node === undefined) {
      node = translations.pl;
      for (const p of parts) node = node?.[p];
    }
    return node;
  };
}
